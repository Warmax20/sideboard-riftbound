# Regenerates legends.js and cards.js from the official Riftbound card gallery.
# Run from the project folder when a new set comes out:
#   powershell -ExecutionPolicy Bypass -File tools\update-data.ps1
# Card sets and their release dates live in sets.js and are edited by hand.

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$enc = New-Object System.Text.UTF8Encoding $false
$today = Get-Date -Format 'yyyy-MM-dd'

$page = (Invoke-WebRequest -Uri 'https://playriftbound.com/en-us/card-gallery/' -UseBasicParsing -UserAgent 'Mozilla/5.0').Content
$json = [regex]::Match($page, '<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', 'Singleline').Groups[1].Value
Add-Type -AssemblyName System.Web.Extensions
$ser = New-Object System.Web.Script.Serialization.JavaScriptSerializer
$ser.MaxJsonLength = [int]::MaxValue
$ser.RecursionLimit = 500
$data = $ser.DeserializeObject($json)

# The card list is the first large array of objects that have a cardType.
function Find-Cards($o, $depth) {
  if ($depth -gt 12) { return $null }
  if ($o -is [System.Collections.IDictionary]) {
    foreach ($k in $o.Keys) {
      $v = $o[$k]
      if ($v -is [array] -and $v.Count -gt 100 -and $v[0] -is [System.Collections.IDictionary] -and $v[0].ContainsKey('cardType')) { return ,$v }
      $r = Find-Cards $v ($depth + 1); if ($r) { return ,$r }
    }
  } elseif ($o -is [array]) {
    foreach ($v in $o) { $r = Find-Cards $v ($depth + 1); if ($r) { return ,$r } }
  }
  return $null
}
$cards = Find-Cards $data 0
if (-not $cards) { throw 'Card list not found: the gallery page layout has changed.' }

# Tags that are regions or tribes rather than the champion's name.
$notChampions = 'Yordle', 'Dog', 'Shurima'
$isLegend = { param($c) [bool]($c.cardType.type | Where-Object { $_.id -eq 'legend' }) }
$champion = { param($c) $c.tags.tags | Where-Object { $notChampions -notcontains $_ } | Select-Object -First 1 }

# The serializer escapes quotes and ampersands as \uXXXX; written out plainly, the files stay readable.
function Unescape($s) { [regex]::Replace($s, '\\u(0027|0026|003c|003e)', { [string][char][Convert]::ToInt32($args[0].Groups[1].Value, 16) }) }

# Legends and their domains.
$domains = [ordered]@{}
foreach ($c in $cards) {
  if (-not (& $isLegend $c)) { continue }
  $name = & $champion $c
  if ($name -and -not $domains.Contains($name)) { $domains[$name] = @($c.domain.values | ForEach-Object { $_.id }) }
}
$names = $domains.Keys | Sort-Object
$legends = "// Riftbound legends, extracted from the official card gallery (playriftbound.com) on $today.`n" +
  "// Generated by tools/update-data.ps1: don't edit by hand.`n" +
  "const LEGENDS = [" + (($names | ForEach-Object { $ser.Serialize($_) }) -join ', ') + "];`n`n" +
  "// Domains of each legend, from the same source. Used for the two-color rings.`n" +
  "const LEGEND_DOMAINS = {`n" + (($names | ForEach-Object { '  ' + $ser.Serialize($_) + ': [' + (($domains[$_] | ForEach-Object { $ser.Serialize($_) }) -join ', ') + ']' }) -join ",`n") + "`n};`n"
[IO.File]::WriteAllText("$root\legends.js", (Unescape $legends), $enc)

# Card name -> image file, preferring the regular printing over showcase and alternate art.
$best = @{}
foreach ($c in $cards) {
  $url = $c.cardImage.url
  if (-not $url) { continue }
  $file = ($url -split '/')[-1] -replace '\?.*$', ''
  $score = [int]$c.collectorNumber / 1000
  if ($c.rarity.value.id -eq 'showcase') { $score += 1000 }
  if ($c.publicCode -match '\*|\d[a-z]/') { $score += 500 }
  $name = $c.name
  if ($c.subtitle) { $name = "$name, $($c.subtitle)" }
  elseif (& $isLegend $c) { $champ = & $champion $c; if ($champ) { $name = "$champ, $name" } }
  if (-not $best.ContainsKey($name) -or $score -lt $best[$name].score) { $best[$name] = @{ score = $score; file = $file } }
}
$lines = $best.Keys | Sort-Object | ForEach-Object { '  [' + $ser.Serialize($_) + ', "' + $best[$_].file + '"]' }
$cardsJs = "// Riftbound cards [name, image file], extracted from the official card gallery (playriftbound.com) on $today.`n" +
  "// Champion units are `"Name, Subtitle`"; legends are `"Champion, Title`". Generated by tools/update-data.ps1.`n" +
  "const CARD_IMG = `"https://cmsassets.rgpub.io/sanity/images/dsfx7636/game_data_live/`";`n" +
  "const CARD_LIST = [`n" + ($lines -join ",`n") + "`n];`n"
[IO.File]::WriteAllText("$root\cards.js", (Unescape $cardsJs), $enc)

$sets = $cards | ForEach-Object { "$($_.set.value.id) $($_.set.value.label)" } | Sort-Object -Unique
"Legends: $($names.Count)  Cards: $($best.Count)"
"Sets in the gallery: $($sets -join ', ')"
